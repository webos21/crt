#!/usr/bin/env python3
"""Regenerate libcrtui/cmake/lvgl_sources.cmake from a fetched LVGL tree.

The list is committed so CMake can configure before LVGL is fetched (the fetch is a build-time dependency of
crtui). Run this after bumping libcrtui/third_party/lvgl/recipe.json, then check it with
tools/test_lvgl_sources.py. Usage: gen_lvgl_sources.py <lvgl source root> [--check]
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPE = ROOT / "libcrtui/third_party/lvgl/recipe.json"
OUTPUT = ROOT / "libcrtui/cmake/lvgl_sources.cmake"


def render(lvgl_root: Path) -> str:
    version = json.loads(RECIPE.read_text(encoding="utf-8"))["version"]
    files = sorted(path.relative_to(lvgl_root).as_posix() for path in (lvgl_root / "src").rglob("*.c"))
    if not files:
        raise SystemExit(f"{lvgl_root}: no src/*.c files (not an extracted LVGL tree)")
    lines = [f"# Generated by tools/gen_lvgl_sources.py for LVGL {version}; do not edit by hand.",
             "# Paths are relative to CRTUI_LVGL_ROOT. libcrtui/third_party/lvgl/recipe.json pins the version.",
             f"set(CRTUI_LVGL_PINNED_VERSION \"{version}\")", "set(CRTUI_LVGL_SOURCE_LIST"]
    lines += [f"  {name}" for name in files]
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("lvgl_root", type=Path)
    parser.add_argument("--check", action="store_true", help="fail if the committed list differs")
    args = parser.parse_args()
    text = render(args.lvgl_root.resolve())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; run tools/gen_lvgl_sources.py {args.lvgl_root}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({text.count(chr(10)) - 5} sources)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

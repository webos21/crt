// The CRT EGL/GLES boundary until GPU buffers arrive (Web Tranche 9).
//
// WebCore and the bundled Skia are written against EGL and OpenGL ES: WebCore's CMake links
// OpenGL::GLES and ${EGL_LIBRARIES} unconditionally, libwpe's CMake requires an EGL library, and
// Skia's Ganesh GL sources always compile. The CRT port paints on the CPU, so no GL context is ever
// created. This library is the explicit "no GPU" implementation of that interface: every entry
// point reports failure the way a driver without a device does (eglGetDisplay returns
// EGL_NO_DISPLAY, eglInitialize returns EGL_FALSE, eglGetError reports EGL_NOT_INITIALIZED, GL calls
// do nothing and return zero or NULL). It is replaced, not extended, by a real EGL in Tranche 9.
//
// The functions take no declared parameters on purpose: on the x86-64 and AArch64 calling
// conventions a function that ignores its arguments and returns zero is call-compatible with every
// EGL/GLES prototype that returns an integer, boolean or pointer, and no EGL/GLES header is needed
// to build this file. (None of these entry points returns a floating-point value.) The name list
// is every function of EGL 1.5 and OpenGL ES 2.0-3.2, taken from the Khronos headers.
//
// Installed as libEGL.so and libGLESv2.so by porting/recipes/crt-egl.json.

